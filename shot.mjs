import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/home/ubuntu/.local/bin/google-chrome', args:['--use-gl=angle','--enable-webgl','--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 900, height: 700 } });
p.on('pageerror', e => console.log('PAGEERR', e.message));
await p.goto('http://localhost:8901/', { waitUntil: 'networkidle' });
await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/claw1.png' });
await p.keyboard.press('Space'); await p.waitForTimeout(1500);
await p.screenshot({ path: '/tmp/claw2.png' });
console.log('ok');
await b.close();
